    def load_lifecycle(self) -> LifecycleSnapshotRecord:
        cursor = self.connection.cursor()
        try:
            cursor.execute(
                """
                SELECT snapshot.monitoring_snapshot_id, snapshot.state,
                       snapshot.cas_version, snapshot.created_at,
                       snapshot.updated_at, episode.episode_json,
                       episode.state, episode.current_revision_id,
                       revision.revision_json, episode.cas_version
                FROM public.backend_monitoring_snapshots_v2 AS snapshot
                LEFT JOIN public.sleep_domain_night_episodes AS episode
                  ON episode.night_episode_id = snapshot.active_night_episode_id
                 AND episode.namespace_id = snapshot.namespace_id
                 AND episode.data_mode = snapshot.data_mode
                LEFT JOIN public.sleep_domain_night_episode_revisions AS revision
                  ON revision.night_episode_revision_id = episode.current_revision_id
                 AND revision.namespace_id = episode.namespace_id
                 AND revision.data_mode = episode.data_mode
                WHERE snapshot.namespace_id = %s AND snapshot.data_mode = %s
                  AND snapshot.namespace_generation = %s
                  AND snapshot.subject_id = %s
                  AND COALESCE(snapshot.run_id, '') = COALESCE(%s, '')
                  AND COALESCE(snapshot.arm_id, '') = COALESCE(%s, '')
                FOR UPDATE OF snapshot
                """,
                (
                    self.scope.namespace_id,
                    self.scope.data_mode,
                    self.scope.namespace_generation,
                    self.scope.subject_id,
                    self.scope.run_id,
                    self.scope.arm_id,
                ),
            )
            row = cursor.fetchone()
        finally:
            cursor.close()
        if row is None:
            return LifecycleSnapshotRecord(
                monitoring_snapshot_id=None,
                state="dormant",
                cas_version=0,
                created_at=None,
                updated_at=None,
            )
        episode: StoredEpisode | None = None
        if row[5] is not None:
            episode_model = NightEpisodeV2.model_validate(_json_value(row[5]))
            revision_payload = _json_value(row[8])
            observation_ids = tuple(
                str(value) for value in revision_payload.get("observation_ids", ())
            )
            episode = StoredEpisode(
                episode=episode_model,
                database_state=str(row[6]),
                current_revision_id=str(row[7]),
                observation_ids=observation_ids,
                cas_version=int(row[9]),
            )
        if str(row[1]) == "active" and episode is None:
            raise SleepSliceInvariantError(
                "active monitoring snapshot has no readable NightEpisode"
            )
        return LifecycleSnapshotRecord(
            monitoring_snapshot_id=str(row[0]),
            state=str(row[1]),  # type: ignore[arg-type]
            cas_version=int(row[2]),
            created_at=row[3],
            updated_at=row[4],
            episode=episode,
        )

