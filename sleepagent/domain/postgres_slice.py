class ReplayObservationInput(SleepDomainContract):
    """Strict replay-adapter payload encrypted in the immutable raw inbox.

    IDs belonging to the provider remain opaque.  Internal raw, candidate and
    canonical IDs are generated by the server when the corresponding stage is
    committed.
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal["replay_observation_input.v1"] = (
        "replay_observation_input.v1"
    )
    provider_id: str = Field(min_length=1, max_length=200)
    provider_account_id: str = Field(min_length=1, max_length=200)
    provider_device_id: str = Field(min_length=1, max_length=500)
    subject_id: str = Field(min_length=1, max_length=200)
    device_id: str = Field(min_length=1, max_length=200)
    device_binding_id: str = Field(min_length=1, max_length=200)
    binding_version: int = Field(ge=1)
    timezone_name: str = Field(min_length=1, max_length=200)
    observation_type: ObservationType
    payload: ObservationPayload
    source_kind: SourceKind
    quality: ObservationQuality
    request_signed_at: datetime | None = None
    measurement_at: datetime | None = None
    event_occurred_at: datetime | None = None
    received_at: datetime
    source_timestamp_text: str | None = Field(default=None, max_length=500)
    timezone_status: TimezoneStatus
    source_key: str = Field(min_length=1, max_length=500)
    idempotency_identity: str = Field(min_length=1, max_length=500)
    source_record_id: str | None = Field(default=None, max_length=500)
    message_id: str | None = Field(default=None, max_length=500)

    @model_validator(mode="after")
    def validate_replay_input(self) -> "ReplayObservationInput":
        if self.payload.observation_type.value != self.observation_type.value:
            raise ValueError("payload observation_type must match envelope")
        if self.measurement_at is None and self.event_occurred_at is None:
            raise ValueError(
                "replay observation requires measurement_at or event_occurred_at"
            )
        try:
            ZoneInfo(self.timezone_name)
        except ZoneInfoNotFoundError as exc:
            raise ValueError("timezone_name must be a valid IANA timezone") from exc
        validate_observation_ontology(
            observation_type=self.observation_type,
            payload=self.payload,
            source_kind=self.source_kind,
        )
        return self

    def canonical_bytes(self) -> bytes:
        return _canonical_json(self.model_dump(mode="json"))


class ReplayRawBatch(SleepDomainContract):
    schema_version: Literal["replay_raw_batch.v1"] = "replay_raw_batch.v1"
    items: tuple[ReplayObservationInput, ...] = Field(
        min_length=1,
        max_length=MAX_REPLAY_INGRESS_BATCH,
    )

    @model_validator(mode="after")
    def idempotency_keys_are_unique(self) -> "ReplayRawBatch":
        keys = [
            (item.provider_account_id, item.idempotency_identity)
            for item in self.items
        ]
        if len(keys) != len(set(keys)):
            raise ValueError("a replay batch cannot repeat an idempotency identity")
        return self


class ReplayIngressOrder(SleepDomainContract):
    """Server-owned ordered stream coordinates for one atomic raw batch."""

    schema_version: Literal["replay_ingress_order.v1"] = (
        "replay_ingress_order.v1"
    )
    journey_id: str = Field(min_length=1)
    manifest_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    stream_key: str = Field(min_length=1, max_length=200)
    first_sequence: int = Field(ge=1)
    predecessor_raw_ingress_record_id: str | None = None
    predecessor_work_id: str | None = None

    @model_validator(mode="after")
    def validate_predecessors(self) -> "ReplayIngressOrder":
        predecessors = (
            self.predecessor_raw_ingress_record_id,
            self.predecessor_work_id,
        )
        if self.first_sequence == 1 and any(predecessors):
            raise ValueError("first replay batch cannot declare predecessors")
        if self.first_sequence > 1 and not all(predecessors):
            raise ValueError("later replay batch requires both predecessors")
        return self


