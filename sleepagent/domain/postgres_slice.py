                cursor,
                event_id=self.id_generator(committed_at),
                event_type="CANONICAL_OBSERVATION_COMMITTED",
                aggregate_type="SleepObservation",
                aggregate_id=observation.observation_id,
                aggregate_version=1,
                sequence=1,
