@dataclass(frozen=True, slots=True)
class SleepSlicePolicy:
    boundary: EpisodeBoundaryPolicy
    quality: DeterministicQualityPolicy
    risk: DeterministicRiskPolicy
    events: FastPathEventPolicy

    @property
    def policy_versions(self) -> dict[str, str]:
        return {
            "boundary": self.boundary.policy_version,
            "quality": self.quality.policy_version,
            "risk": self.risk.policy_version,
            "fast_path_event": self.events.policy_version,
        }

    @property
    def policy_sha256(self) -> str:
        return hashlib.sha256(
            _canonical_json(
                {
                    "boundary": self.boundary.model_dump(mode="json"),
                    "quality": self.quality.model_dump(mode="json"),
                    "risk": self.risk.model_dump(mode="json"),
                    "events": self.events.model_dump(mode="json"),
                }
            )
        ).hexdigest()

    def deterministic_deadline(
        self,
        opened_at: datetime,
        timezone_name: str,
    ) -> datetime:
        zone = ZoneInfo(timezone_name)
        local_open = opened_at.astimezone(zone)
        minute = self.boundary.report_deadline_local_minute
        candidate_wall = datetime.combine(
            local_open.date(),
            time(hour=minute // 60, minute=minute % 60),
        )
        if candidate_wall <= local_open.replace(tzinfo=None):
            candidate_wall += timedelta(days=1)
        candidate = _resolve_unique_local_wall_time(
            candidate_wall,
            zone,
            label="deterministic close deadline",
        )
        maximum = opened_at + timedelta(
            seconds=self.boundary.maximum_episode_seconds
        )
        return min(candidate.astimezone(UTC), maximum.astimezone(UTC))


