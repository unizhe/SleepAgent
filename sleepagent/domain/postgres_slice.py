    def acquire_subject_lifecycle_lease(
        self,
        namespace: DomainNamespace,
        *,
        subject_id: str,
        lease_owner: str,
        lease_token: str,
        now: datetime,
        lease_duration: timedelta,
    ) -> SubjectLifecycleLease:
        self._require_namespace(namespace)
        if subject_id != self.scope.subject_id:
            raise SleepSliceInvariantError("fast-path lease subject mismatch")
        # The durable Operation row is already locked and fenced in this UoW.
        return SubjectLifecycleLease(
            subject_id=subject_id,
            lease_owner=lease_owner,
            lease_token=lease_token,
            lease_expires_at=now + lease_duration,
        )

    def release_subject_lifecycle_lease(
        self,
        namespace: DomainNamespace,
        lease: SubjectLifecycleLease,
    ) -> bool:
        self._require_namespace(namespace)
        return lease.subject_id == self.scope.subject_id

    def next_domain_event_sequence(
        self,
        namespace: DomainNamespace,
        *,
        aggregate_type: str,
        aggregate_id: str,
    ) -> int:
        self._require_namespace(namespace)
        row = self._fetchone(
            """
            SELECT COALESCE(MAX(per_aggregate_sequence), 0) + 1
            FROM public.sleep_domain_domain_outbox
            WHERE namespace_id = %s AND data_mode = %s
              AND aggregate_type = %s AND aggregate_id = %s
            """,
            (
                self.scope.namespace_id,
                self.scope.data_mode,
                aggregate_type,
                aggregate_id,
            ),
        )
        return 1 if row is None else int(row[0])

