    def get_night_episode(
        self,
        namespace: DomainNamespace,
        *,
        night_episode_id: str,
    ) -> NightEpisode | None:
        self._require_namespace(namespace)
        cursor = self.connection.cursor()
        try:
            cursor.execute(
                """
                SELECT episode.episode_json, episode.state,
                       episode.current_revision_id,
                       revision.revision_json, episode.created_at,
                       episode.updated_at
                FROM public.sleep_domain_night_episodes AS episode
                LEFT JOIN public.sleep_domain_night_episode_revisions AS revision
                  ON revision.night_episode_revision_id = episode.current_revision_id
                 AND revision.namespace_id = episode.namespace_id
                 AND revision.data_mode = episode.data_mode
                WHERE episode.night_episode_id = %s
                  AND episode.namespace_id = %s AND episode.data_mode = %s
                  AND episode.namespace_generation = %s
                  AND episode.subject_id = %s
                  AND episode.protocol_version >= 2
                """,
                (
                    night_episode_id,
                    self.scope.namespace_id,
                    self.scope.data_mode,
                    self.scope.namespace_generation,
                    self.scope.subject_id,
                ),
            )
            row = cursor.fetchone()
        finally:
            cursor.close()
        if row is None:
            return None
        episode = NightEpisodeV2.model_validate(_json_value(row[0]))
        revision_payload = _json_value(row[3])
        observation_ids = tuple(
            str(item) for item in revision_payload.get("observation_ids", ())
        )
        observations = tuple(
            item
            for observation_id in observation_ids
            if (item := self.get_observation(namespace, observation_id=observation_id))
            is not None
        )
        references = tuple(
            DeviceBindingReference(
                device_binding_id=binding_id,
                binding_version=binding_version,
                device_id=device_id,
            )
            for binding_id, binding_version, device_id in sorted(
                {
                    (
                        item.device_binding_id,
                        item.binding_version,
                        item.device_id,
                    )
                    for item in observations
                }
            )
        )
        if not references or episode.episode_local_date is None:
            raise SleepSliceInvariantError(
                "fast path requires a finalized Episode with bound observations"
            )
        end_at = episode.wake_at or episode.deterministic_close_deadline_at
        policies = revision_payload.get("policy_versions") or {}
        adapters = {
            item.provenance.adapter_id: item.provenance.adapter_version
            for item in observations
        }
        return NightEpisode(
            night_episode_id=episode.night_episode_id,
            data_mode=episode.data_mode,
            subject_id=episode.subject_id,
            timezone_name=episode.timezone_name,
            local_sleep_date=(
                episode.legacy_local_sleep_date or episode.bed_local_date
                or episode.episode_local_date
            ),
            night_key=f"v2:{episode.episode_anchor_key}",
            collection_start_at=episode.collection_start_at,
            collection_end_at=end_at,
            allowed_lateness_watermark_at=end_at
            + timedelta(seconds=7_200),
            report_deadline_at=episode.deterministic_close_deadline_at,
            collection_window_derivation=(
                CollectionWindowDerivation.VERIFIED_IN_BED
            ),
            binding_references=references,
            observation_ids=observation_ids,
            night_episode_revision_ids=(str(row[2]),),
            data_sufficiency=DataSufficiency.REPORT_PENDING,
            pinned_adapter_versions=adapters or {"replay-adapter": "1"},
            pinned_observation_schema_versions=("sleep_observation.v1",),
            pinned_policy_versions={
                "quality": str(policies.get("quality", "quality-v1")),
                "risk": str(policies.get("risk", "risk-v1")),
                "fast_path_event": str(
                    policies.get("fast_path_event", "fast-path-event-v1")
                ),
            },
            state=NightEpisodeState(str(row[1])),
            current_night_episode_revision_id=str(row[2]),
            created_at=row[4],
            updated_at=row[5],
        )

    def lock_fast_path_episode_revision(
        self,
        operation: LoadedFastPathOperation,
    ) -> None:
        pinned_revision = operation.operation_json.get(
            "night_episode_revision_id"
        )
        if not isinstance(pinned_revision, str) or not pinned_revision:
            raise SleepSliceInvariantError(
                "fast-path operation has no pinned Episode revision"
            )
        cursor = self.connection.cursor()
        try:
            cursor.execute(
                """
                SELECT current_revision_id
                FROM public.sleep_domain_night_episodes
                WHERE night_episode_id = %s AND namespace_id = %s
                  AND data_mode = %s AND namespace_generation = %s
                  AND subject_id = %s
                  AND COALESCE(run_id, '') = COALESCE(%s, '')
                  AND COALESCE(arm_id, '') = COALESCE(%s, '')
                  AND protocol_version >= 2
                FOR UPDATE
                """,
                (
                    operation.night_episode_id,
                    self.scope.namespace_id,
                    self.scope.data_mode,
                    self.scope.namespace_generation,
                    self.scope.subject_id,
                    self.scope.run_id,
                    self.scope.arm_id,
                ),
            )
            row = cursor.fetchone()
        finally:
            cursor.close()
        if row is None:
            raise SleepSliceInvariantError(
                "fast-path Episode is unavailable in the exact work scope"
            )
        if str(row[0]) != pinned_revision:
            raise SleepSliceStaleRevision(
                "fast-path operation targets a superseded Episode revision"
            )

