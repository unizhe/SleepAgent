def _resolve_unique_local_wall_time(
    wall_time: datetime,
    zone: ZoneInfo,
    *,
    label: str,
) -> datetime:
    if wall_time.tzinfo is not None:
        raise ValueError("wall_time must be timezone-naive")
    candidates: dict[datetime, datetime] = {}
    for fold in (0, 1):
        local = wall_time.replace(tzinfo=zone, fold=fold)
        normalized = local.astimezone(UTC).astimezone(zone)
        if normalized.replace(tzinfo=None) == wall_time:
            candidates[local.astimezone(UTC)] = local
    if not candidates:
        raise SleepSliceInvariantError(
            f"{label} falls in a nonexistent local-time gap"
        )
    if len(candidates) != 1:
        raise SleepSliceInvariantError(
            f"{label} is ambiguous without an explicit DST fold"
        )
    return next(iter(candidates.values()))


def _date_state(episode: NightEpisodeV2) -> str:
    if episode.publication_status == EpisodePublicationStatus.PROVISIONAL:
        return "provisional"
    if episode.publication_status == EpisodePublicationStatus.COMMITTED:
        return "finalized"
    return "conflict"


def _assignment_estimated(episode: NightEpisodeV2) -> bool | None:
    if episode.assignment_basis == EpisodeAssignmentBasis.PROVISIONAL:
        return None
    return episode.assignment_basis == EpisodeAssignmentBasis.DEADLINE_FALLBACK


def _digest(value: Mapping[str, Any]) -> str:
    return hashlib.sha256(_canonical_json(value)).hexdigest()


def _canonical_json(value: Any) -> bytes:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")


def _json(value: Any) -> str:
    return _canonical_json(value).decode("utf-8")


def _json_value(value: Any) -> dict[str, Any]:
    if isinstance(value, Mapping):
        return dict(value)
    if isinstance(value, (bytes, bytearray, memoryview)):
        value = bytes(value).decode("utf-8")
    decoded = json.loads(str(value))
    if not isinstance(decoded, dict):
        raise SleepSliceInvariantError("database JSON value is not an object")
    return decoded


def _require_aware(value: datetime, name: str) -> None:
    if value.tzinfo is None or value.utcoffset() is None:
        raise ValueError(f"{name} must be timezone-aware")


