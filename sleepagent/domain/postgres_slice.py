# 本模块负责睡眠领域规则与数据语义，不依赖 HTTP 或进程装配。
"""PostgreSQL-backed B3 sleep vertical slice.

The module is deliberately an application/persistence adapter around the
existing sleep-domain contracts.  It owns no connection lifecycle and never
commits from a repository method.  The three public handlers below are the
transaction boundaries described by the backend plan:

* replay raw record + intake receipt + normalization work + outbox;
* canonical observation + lifecycle/Episode revision + fast-path operation;
* deterministic quality/risk + urgent result or product-agent operation.

Provider/model calls are intentionally absent.  In particular the urgent
branch is structurally zero-model: it can only commit deterministic results.
"""

